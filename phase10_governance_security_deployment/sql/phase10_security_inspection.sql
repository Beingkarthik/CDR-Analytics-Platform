
-- PHASE 10: SECURITY ENVIRONMENT INSPECTION
-- Project: CDR Analytics Platform

USE ROLE ACCOUNTADMIN;
USE DATABASE CDR_ANALYTICS;
USE WAREHOUSE COMPUTE_WH;

-- 1. Current session details
SELECT
    CURRENT_USER() AS CURRENT_USER,
    CURRENT_ROLE() AS CURRENT_ROLE,
    CURRENT_DATABASE() AS CURRENT_DATABASE,
    CURRENT_SCHEMA() AS CURRENT_SCHEMA,
    CURRENT_WAREHOUSE() AS CURRENT_WAREHOUSE;

-- 2. Existing schemas
SHOW SCHEMAS IN DATABASE CDR_ANALYTICS;

-- 3. Existing roles
SHOW ROLES;

-- 4. Tables in RAW
SHOW TABLES IN SCHEMA CDR_ANALYTICS.RAW;

-- 5. Tables in DBT_DEV
SHOW TABLES IN SCHEMA CDR_ANALYTICS.DBT_DEV;

-- 6. Inspect available columns
SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE
FROM CDR_ANALYTICS.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA IN ('RAW', 'DBT_DEV')
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;
