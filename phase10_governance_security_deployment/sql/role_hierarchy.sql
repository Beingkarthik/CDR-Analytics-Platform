-- PHASE 10: ROLE HIERARCHY
-- Run with ACCOUNTADMIN privileges.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS CDR_ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS CDR_DEV_ROLE;
CREATE ROLE IF NOT EXISTS CDR_PROD_ROLE;
CREATE ROLE IF NOT EXISTS CDR_SECURITY_ADMIN_ROLE;
CREATE ROLE IF NOT EXISTS CDR_DEPLOY_ROLE;

GRANT ROLE CDR_ANALYST_ROLE TO ROLE CDR_DEV_ROLE;
GRANT ROLE CDR_ANALYST_ROLE TO ROLE CDR_PROD_ROLE;
GRANT ROLE CDR_DEV_ROLE TO ROLE SYSADMIN;
GRANT ROLE CDR_PROD_ROLE TO ROLE SYSADMIN;
GRANT ROLE CDR_SECURITY_ADMIN_ROLE TO ROLE SECURITYADMIN;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE CDR_ANALYST_ROLE;
GRANT USAGE ON DATABASE CDR_ANALYTICS TO ROLE CDR_ANALYST_ROLE;
GRANT USAGE ON SCHEMA CDR_ANALYTICS.DBT_DEV TO ROLE CDR_ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA CDR_ANALYTICS.DBT_DEV TO ROLE CDR_ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CDR_ANALYTICS.DBT_DEV TO ROLE CDR_ANALYST_ROLE;
