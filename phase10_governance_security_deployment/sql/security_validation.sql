-- PHASE 10: SECURITY VALIDATION
USE ROLE ACCOUNTADMIN;
USE DATABASE CDR_ANALYTICS;

-- Confirm roles exist
SHOW ROLES LIKE 'CDR_%';

-- Confirm security demo objects exist
SHOW TABLES LIKE 'CUSTOMER_PII_TEST' IN SCHEMA CDR_ANALYTICS.SECURITY_DEMO;
SHOW VIEWS LIKE 'V_CUSTOMER_PII_MASKED' IN SCHEMA CDR_ANALYTICS.SECURITY_DEMO;

-- Confirm the secure view property
SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, IS_SECURE
FROM CDR_ANALYTICS.INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA = 'SECURITY_DEMO'
  AND TABLE_NAME = 'V_CUSTOMER_PII_MASKED';

-- Inspect masked-view output using analyst role
USE ROLE CDR_ANALYST_ROLE;
SELECT * FROM CDR_ANALYTICS.SECURITY_DEMO.V_CUSTOMER_PII_MASKED;

-- Inspect authorized output using security administrator role
USE ROLE CDR_SECURITY_ADMIN_ROLE;
SELECT * FROM CDR_ANALYTICS.SECURITY_DEMO.V_CUSTOMER_PII_MASKED;
