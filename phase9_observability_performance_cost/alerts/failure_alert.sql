-- CDR pipeline failure alert
USE ROLE ACCOUNTADMIN;
USE DATABASE CDR_ANALYTICS;
USE SCHEMA RAW;

CREATE OR REPLACE ALERT CDR_PIPELINE_FAILURE_ALERT
WAREHOUSE = COMPUTE_WH
SCHEDULE = '5 MINUTE'
IF (EXISTS (
 SELECT 1 FROM TABLE(CDR_ANALYTICS.INFORMATION_SCHEMA.QUERY_HISTORY(
 END_TIME_RANGE_START => DATEADD('MINUTE', -10, CURRENT_TIMESTAMP()), RESULT_LIMIT => 100
 ))
 WHERE EXECUTION_STATUS = 'FAIL' AND QUERY_TEXT ILIKE '%CDR%'
))
THEN CALL SYSTEM$SEND_EMAIL(
 'CDR_ALERT_EMAIL', 'nanavathkarthik@gmail.com',
 'CDR Pipeline Failure Alert',
 'A failed CDR-related query was detected.'
);

ALTER ALERT CDR_ANALYTICS.RAW.CDR_PIPELINE_FAILURE_ALERT RESUME;
