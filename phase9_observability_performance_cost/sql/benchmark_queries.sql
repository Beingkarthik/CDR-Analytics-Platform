-- Phase 9 benchmark query variants
ALTER SESSION SET USE_CACHED_RESULT = FALSE;

-- Baseline
ALTER SESSION SET QUERY_TAG = 'PHASE9_OPT1_BASELINE';
SELECT COUNT(*), SUM(DURATION_SECONDS), SUM(ESTIMATED_CHARGE_PENCE), AVG(DURATION_SECONDS)
FROM CDR_ANALYTICS.DBT_DEV.FACT_CDR_EVENTS;

-- Non-negative duration filter
ALTER SESSION SET QUERY_TAG = 'PHASE9_OPT1_OPTIMIZED';
SELECT COUNT(*), SUM(DURATION_SECONDS), SUM(ESTIMATED_CHARGE_PENCE), AVG(DURATION_SECONDS)
FROM CDR_ANALYTICS.DBT_DEV.FACT_CDR_EVENTS WHERE DURATION_SECONDS >= 0;

-- Column reduction
ALTER SESSION SET QUERY_TAG = 'PHASE9_OPT2_COLUMN_REDUCTION';
SELECT COUNT(*), SUM(DURATION_SECONDS)
FROM CDR_ANALYTICS.DBT_DEV.FACT_CDR_EVENTS;

-- Filtered aggregation
ALTER SESSION SET QUERY_TAG = 'PHASE9_OPT3_FILTERED';
SELECT COUNT(*), SUM(DURATION_SECONDS)
FROM CDR_ANALYTICS.DBT_DEV.FACT_CDR_EVENTS
WHERE DURATION_SECONDS BETWEEN 0 AND 1000;
