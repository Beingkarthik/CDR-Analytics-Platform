-- Phase 9 warehouse cost analysis
SELECT WAREHOUSE_NAME, SUM(CREDITS_USED) AS TOTAL_CREDITS,
SUM(CREDITS_USED_COMPUTE) AS COMPUTE_CREDITS,
SUM(CREDITS_USED_CLOUD_SERVICES) AS CLOUD_SERVICES_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
AND WAREHOUSE_NAME = 'COMPUTE_WH'
GROUP BY WAREHOUSE_NAME;

-- Daily warehouse usage
SELECT TO_DATE(START_TIME) AS USAGE_DATE,
WAREHOUSE_NAME, SUM(CREDITS_USED) AS DAILY_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
AND WAREHOUSE_NAME = 'COMPUTE_WH'
GROUP BY TO_DATE(START_TIME), WAREHOUSE_NAME
ORDER BY USAGE_DATE;
