-- PHASE 9: OBSERVABILITY MONITORING
-- CDR Analytics Platform

USE DATABASE CDR_ANALYTICS;
USE SCHEMA DBT_DEV;

-- 1. RAW TABLE RECORD COUNT
SELECT
    COUNT(*) AS RAW_CDR_COUNT,
    CURRENT_TIMESTAMP() AS CHECKED_AT
FROM CDR_ANALYTICS.RAW.CDR_RECORDS;


-- 2. GOLD FACT TABLE RECORD COUNT
SELECT
    COUNT(*) AS FACT_CDR_COUNT,
    CURRENT_TIMESTAMP() AS CHECKED_AT
FROM CDR_ANALYTICS.DBT_DEV.FACT_CDR_EVENTS;


-- 3. INVALID CDR RECORDS
SELECT
    COUNT(*) AS INVALID_RECORD_COUNT
FROM CDR_ANALYTICS.RAW.CDR_RECORDS
WHERE CDR_ID IS NULL
   OR DURATION_SECONDS < 0;


-- 4. QUERY FAILURE MONITORING
SELECT
    QUERY_ID,
    START_TIME,
    EXECUTION_STATUS,
    ERROR_MESSAGE,
    QUERY_TEXT
FROM TABLE(
    CDR_ANALYTICS.INFORMATION_SCHEMA.QUERY_HISTORY(
        END_TIME_RANGE_START =>
            DATEADD('HOUR', -24, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 100
    )
)
WHERE EXECUTION_STATUS = 'FAIL'
ORDER BY START_TIME DESC;


-- 5. QUERY PERFORMANCE MONITORING
SELECT
    QUERY_ID,
    START_TIME,
    EXECUTION_TIME AS EXECUTION_TIME_MS,
    BYTES_SCANNED,
    ROWS_PRODUCED,
    EXECUTION_STATUS
FROM TABLE(
    CDR_ANALYTICS.INFORMATION_SCHEMA.QUERY_HISTORY(
        END_TIME_RANGE_START =>
            DATEADD('HOUR', -24, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 100
    )
)
WHERE QUERY_TEXT ILIKE '%CDR_ANALYTICS%'
ORDER BY EXECUTION_TIME DESC;